export function getWindowCell(index: number): WindowCell {
  const cell = windowCells[index];
  if (!cell) throw new RangeError(`Window shape has no pane ${index}`);
  return cell;
}

/** CSS `mask-image` value that cuts content to a single pane (stretched to the element box). */
export function windowPaneMask(index: number): string {
  const { d, x, y, width, height } = getWindowCell(index);
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${x} ${y} ${width} ${height}" preserveAspectRatio="none"><path d="${d}"/></svg>`;
  return `url("data:image/svg+xml,${encodeURIComponent(svg)}")`;
}

/** The pane's outline as a `clip-path: polygon(...)` value, for masking content to that pane. */
export function windowPanePolygon(index: number): string {
  return getWindowCell(index).polygon;
}

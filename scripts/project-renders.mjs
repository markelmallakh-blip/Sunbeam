// Builds the project-page images for projects without a hand-made case study.
// Picks evenly spaced renders from each project's folder in the brand assets, converts them to
// WebP in public/images/projects/<slug>/, and writes src/content/project-renders.ts.
//   node scripts/project-renders.mjs
import { readdirSync, statSync, mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import sharp from "sharp";

const ASSETS = "/Users/markamir/Desktop/Mark/Sunbeam";
const projects = {
  "sodic-villette": "Residential/Villas/Sodic-Villette",
  "la7-zoya-gym": "Commercial/Gym & Clubhouse/LA7 Renders",
  "palm-hills-october": "Residential/Villas/Palm Hills October",
  wndr: "Commercial/F&B/WNDR Renders",
  "pottery-cafe": "Commercial/F&B/Pottery Renders",
};

const images = (dir) =>
  readdirSync(dir)
    .flatMap((name) => {
      const path = join(dir, name);
      if (statSync(path).isDirectory()) return images(path);
      return /\.(jpe?g|png|webp)$/i.test(name) && !/toilet|bath/i.test(path) ? [path] : [];
    })
    .sort();

const pick = (list, count) =>
  Array.from(
    { length: Math.min(count, list.length) },
    (_, i) => list[Math.floor((i * list.length) / Math.min(count, list.length))],
  );

const manifest = {};
for (const [slug, folder] of Object.entries(projects)) {
  const all = images(join(ASSETS, folder));
  const chosen = pick(all, 12);
  const out = `public/images/projects/${slug}`;
  mkdirSync(out, { recursive: true });
  const save = async (source, name, width) => {
    const info = await sharp(source)
      .rotate()
      .resize({ width, withoutEnlargement: true })
      .webp({ quality: 80 })
      .toFile(`${out}/${name}.webp`);
    return { src: `/images/projects/${slug}/${name}.webp`, width: info.width, height: info.height };
  };
  // First two for the brief, next two for "What we deliver", the rest for the gallery.
  const [b1, b2, d1, d2, ...rest] = chosen;
  manifest[slug] = {
    brief: [await save(b1, "brief-1", 1400), await save(b2, "brief-2", 1400)],
    deliver: [await save(d1, "deliver-1", 1600), await save(d2, "deliver-2", 1600)],
    gallery: await Promise.all(
      rest
        .slice(0, 8)
        .map((source, i) => save(source, `gallery-${String(i + 1).padStart(2, "0")}`, 1000)),
    ),
  };
  console.log(slug, all.length, "renders →", 4 + manifest[slug].gallery.length, "images");
}

writeFileSync(
  "src/content/project-renders.ts",
  `/* Generated by scripts/project-renders.mjs — re-run it rather than editing by hand. */\n\n` +
    `export type RenderFile = { src: string; width: number; height: number };\n\n` +
    `export const projectRenders: Record<\n  string,\n  { brief: RenderFile[]; deliver: RenderFile[]; gallery: RenderFile[] }\n> = ${JSON.stringify(manifest, null, 2)};\n`,
);
